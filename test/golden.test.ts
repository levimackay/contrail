/**
 * Every report, byte for byte, as it was printed before the query path was made faster: the demo
 * sessions and a smaller copy of the long benchmark session, through the CLI. The clock and the
 * time zone are fixed so git's commit ids and every printed time are the same on every run; the
 * temporary directories are the only thing replaced before comparing.
 * CONTRAIL_GOLDEN_WRITE=1 rewrites test/fixtures/golden/ from the current code.
 */

const NOW_MS = Date.UTC(2026, 8, 1, 12, 0, 0);
Date.now = () => NOW_MS;
process.env.TZ = 'UTC';

const GOLDEN = join(import.meta.dirname, 'fixtures', 'golden');
const WRITE = process.env.CONTRAIL_GOLDEN_WRITE === '1';

interface Case {
  name: string;
  argv: string[];
  stdin?: string;
}

let root = '';
let demo: { repo: string; data: string; sha: string };
let long: { cwd: string; data: string };

before(() => {
  root = realpathSync(mkdtempSync(join(tmpdir(), 'contrail-golden-')));
  demo = buildDemo(join(root, 'demo'));
  const cwd = join(root, 'long', 'ledger');
  mkdirSync(cwd, { recursive: true });
  const data = join(root, 'long', 'data');
  writeSpool(data, [{ id: LONG_SESSION, drafts: longDrafts(cwd, { scale: 0.1 }), cwd }], Math.floor(NOW_MS / 1000) - 3 * 3600);
  long = { cwd, data };
});

async function render(cases: Case[], data: string, cwd: string): Promise<Map<string, string>> {
  const out = new Map<string, string>();
  for (const c of cases) {
    let text = '';
    let err = '';
    const io: Io = { out: s => (text += s), err: s => (err += s), cwd, env: {}, home: '/Users/dev', ...(c.stdin !== undefined ? { stdin: () => c.stdin! } : {}) };
    const code = await main([...c.argv, '--data', data], io);
    const shown = `exit ${code}\n${text}${err ? `--- stderr\n${err}` : ''}`
      .replaceAll(root, '<tmp>')
      .replace(/(Generated by Contrail \S+ on )\d{4}-\d{2}-\d{2}/g, '$1<date>');
    out.set(c.name, shown);
  }
  return out;
}

/** One file per data set: each report under a header line that names it. */
const SEP = '\n@@@@@ ';
/** A report longer than this is kept as its length and digest (trace --json holds every response). */
const MAX_KEPT = 64 * 1024;

function compare(file: string, rendered: Map<string, string>): void {
  const actual = new Map(
    [...rendered].map(([name, text]) => [name, text.length > MAX_KEPT ? `${text.length} characters, sha256 ${createHash('sha256').update(text).digest('hex')}\n` : text]),
  );
  const path = join(GOLDEN, file);
  if (WRITE) {
    mkdirSync(GOLDEN, { recursive: true });
    writeFileSync(path, [...actual].map(([name, text]) => `${SEP}${name}\n${text}`).join(''));
    return;
  }
  assert.ok(existsSync(path), `${path} is missing; run the tests once with CONTRAIL_GOLDEN_WRITE=1`);
  const expected = new Map(
    readFileSync(path, 'utf8')
      .split(SEP)
      .slice(1)
      .map(part => {
        const nl = part.indexOf('\n');
        return [part.slice(0, nl), part.slice(nl + 1)] as const;
      }),
  );
  assert.deepEqual([...actual.keys()], [...expected.keys()]);
  for (const [name, text] of actual) assert.equal(text, expected.get(name), `${file}: ${name}`);
}

